#!/usr/bin/env node
// Generates src/blogMeta.ts from blogs/*.md (NO body). Runs as a `prebuild`
// step so the metadata index ships in the main bundle while article bodies
// stay in on-demand chunks. All derivation lives in scripts/lib/content.mjs.
import { writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { readArticles } from './lib/content.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'src', 'blogMeta.ts')

const metas = readArticles(root)

writeFileSync(
  out,
  '// AUTO-GENERATED by scripts/gen-blog-index.mjs — do not edit by hand.\n' +
    'export interface ArticleMeta {\n' +
    '  slug: string\n  season: number\n  episode: number\n  title: string\n' +
    '  seoTitle: string\n  deck: string\n  minutes: number\n  date: string | null\n  ogImage: string | null\n}\n\n' +
    `export const articleMetas: ArticleMeta[] = ${JSON.stringify(metas, null, 2)}\n`,
)
console.log(`gen-blog-index: wrote ${metas.length} articles to src/blogMeta.ts`)
